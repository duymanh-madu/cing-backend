/* ==========================================================
 * 9. STRUCTURAL SAFETY ASSERTIONS
 * ========================================================== */

do $migration$
begin

  if not exists (
    select 1
    from
      public.cing_wallet_topup_promotion_config
    where
      id = 1
      and enabled = false
  ) then
    raise exception
      'CING_WALLET_PROMOTION_SAFE_DEFAULT_MISSING';
  end if;


  if exists (
    select 1
    from
      public.cing_wallet_topup_promotion_tiers
  ) then
    raise exception
      'CING_WALLET_PROMOTION_UNEXPECTED_INITIAL_TIERS';
  end if;


  /*
   * This foundation must not replace or redefine the live
   * top-up settlement function.
   */
  if to_regprocedure(
    'public.cing_wallet_settle_verified_topup_atomic(bigint)'
  ) is null
  then
    raise exception
      'CING_WALLET_EXISTING_TOPUP_AUTHORITY_MISSING';
  end if;

end;
$migration$;


commit;
