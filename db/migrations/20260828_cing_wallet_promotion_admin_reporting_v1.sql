/* ==========================================================
 * 7. ADMIN WALLET REPORTING
 *
 * Period metrics:
 * - real-money top-up
 * - promotion bonus
 * - Wallet spending
 * - refunds / reversals
 * - admin adjustment net
 *
 * Current liability:
 * - current account count
 * - current total Wallet balance
 *
 * Reports never mutate financial state.
 * ========================================================== */

create or replace function
public.cing_wallet_admin_summary_v1(
  p_from timestamptz,
  p_to timestamptz
)
returns jsonb
language plpgsql
security definer
set search_path = public
stable
as $$
declare
  v_from timestamptz :=
    p_from;

  v_to timestamptz :=
    p_to;

  v_result jsonb;
begin

  if v_from is not null
     and v_to is not null
     and v_to <= v_from
  then
    raise exception
      'CING_WALLET_REPORT_TIME_RANGE_INVALID'
      using errcode = '22023';
  end if;


  select jsonb_build_object(

    'period',
      jsonb_build_object(
        'from',
          v_from,

        'to',
          v_to
      ),

    'current',
      jsonb_build_object(
        'account_count',
          (
            select count(*)
            from
              public.cing_wallet_accounts
          ),

        'total_wallet_balance',
          (
            select
              coalesce(
                sum(balance),
                0
              )
            from
              public.cing_wallet_accounts
          )
      ),

    'period_totals',
      jsonb_build_object(

        'real_money_topup',
          (
            select
              coalesce(
                sum(amount),
                0
              )
            from
              public.cing_wallet_transactions wt
            where
              wt.transaction_type =
                'topup'
              and (
                v_from is null
                or wt.created_at >=
                  v_from
              )
              and (
                v_to is null
                or wt.created_at <
                  v_to
              )
          ),

        'promotion_bonus',
          (
            select
              coalesce(
                sum(amount),
                0
              )
            from
              public.cing_wallet_transactions wt
            where
              wt.transaction_type =
                'topup_promotion'
              and (
                v_from is null
                or wt.created_at >=
                  v_from
              )
              and (
                v_to is null
                or wt.created_at <
                  v_to
              )
          ),

        'wallet_spending',
          (
            select
              coalesce(
                sum(-amount),
                0
              )
            from
              public.cing_wallet_transactions wt
            where
              wt.transaction_type =
                'payment'
              and (
                v_from is null
                or wt.created_at >=
                  v_from
              )
              and (
                v_to is null
                or wt.created_at <
                  v_to
              )
          ),

        'refunds',
          (
            select
              coalesce(
                sum(amount),
                0
              )
            from
              public.cing_wallet_transactions wt
            where
              wt.transaction_type =
                'refund'
              and (
                v_from is null
                or wt.created_at >=
                  v_from
              )
              and (
                v_to is null
                or wt.created_at <
                  v_to
              )
          ),

        'reversals',
          (
            select
              coalesce(
                sum(amount),
                0
              )
            from
              public.cing_wallet_transactions wt
            where
              wt.transaction_type =
                'reversal'
              and (
                v_from is null
                or wt.created_at >=
                  v_from
              )
              and (
                v_to is null
                or wt.created_at <
                  v_to
              )
          ),

        'admin_adjustment_net',
          (
            select
              coalesce(
                sum(amount),
                0
              )
            from
              public.cing_wallet_transactions wt
            where
              wt.transaction_type =
                'admin_adjustment'
              and (
                v_from is null
                or wt.created_at >=
                  v_from
              )
              and (
                v_to is null
                or wt.created_at <
                  v_to
              )
          ),

        'transaction_count',
          (
            select
              count(*)
            from
              public.cing_wallet_transactions wt
            where
              (
                v_from is null
                or wt.created_at >=
                  v_from
              )
              and (
                v_to is null
                or wt.created_at <
                  v_to
              )
          )
      )
  )
  into v_result;


  return v_result;

end;
$$;


