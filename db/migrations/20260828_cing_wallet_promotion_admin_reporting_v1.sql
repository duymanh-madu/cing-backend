/*
 * ==========================================================
 * CING WALLET — TOPUP PROMOTION + ADMIN REPORTING V1
 * ==========================================================
 *
 * Scope:
 *
 * 1. Current top-up promotion configuration.
 * 2. Threshold tiers.
 * 3. Immutable configuration history.
 * 4. Backend-only Wallet reporting.
 *
 * IMPORTANT:
 *
 * This migration DOES NOT modify the existing verified top-up
 * settlement authority.
 *
 * Therefore applying this migration cannot award promotion
 * money to any customer.
 *
 * Promotion is created disabled and with zero tiers.
 */


/* ==========================================================
 * 1. CURRENT PROMOTION CONFIG
 * ========================================================== */

create table
if not exists
public.cing_wallet_topup_promotion_config (
  id smallint primary key,

  enabled boolean
    not null
    default false,

  name text,

  starts_at timestamptz,

  ends_at timestamptz,

  updated_by text,

  created_at timestamptz
    not null
    default now(),

  updated_at timestamptz
    not null
    default now(),

  constraint
    cing_wallet_topup_promotion_config_singleton_ck
    check (id = 1),

  constraint
    cing_wallet_topup_promotion_config_window_ck
    check (
      starts_at is null
      or ends_at is null
      or ends_at > starts_at
    )
);

insert into
public.cing_wallet_topup_promotion_config (
  id,
  enabled,
  name,
  starts_at,
  ends_at,
  updated_by
)
values (
  1,
  false,
  null,
  null,
  null,
  null
)
on conflict (id)
do nothing;


/* ==========================================================
 * 2. PROMOTION TIERS
 *
 * min_topup_amount:
 * minimum real-money top-up amount required for the tier.
 *
 * bonus_amount:
 * additional Cing Wallet value credited by the promotion.
 *
 * Example semantics:
 *
 * min=1000000 bonus=200000
 * means top up >= 1,000,000 VND qualifies for +200,000.
 *
 * Later settlement authority will choose the highest qualified
 * min_topup_amount.
 * ========================================================== */

create table
if not exists
public.cing_wallet_topup_promotion_tiers (
  id uuid
    primary key
    default gen_random_uuid(),

  config_id smallint
    not null
    default 1
    references
      public.cing_wallet_topup_promotion_config(id)
    on delete restrict,

  min_topup_amount bigint
    not null,

  bonus_amount bigint
    not null,

  created_at timestamptz
    not null
    default now(),

  constraint
    cing_wallet_topup_promotion_tiers_config_ck
    check (config_id = 1),

  constraint
    cing_wallet_topup_promotion_tiers_min_ck
    check (min_topup_amount > 0),

  constraint
    cing_wallet_topup_promotion_tiers_bonus_ck
    check (bonus_amount > 0),

  constraint
    cing_wallet_topup_promotion_tiers_amount_uq
    unique (
      config_id,
      min_topup_amount
    )
);

create index
if not exists
cing_wallet_topup_promotion_tiers_lookup_idx
on public.cing_wallet_topup_promotion_tiers (
  config_id,
  min_topup_amount desc
);


/* ==========================================================
 * 3. IMMUTABLE CONFIGURATION HISTORY
 *
 * Every admin configuration mutation writes a complete JSONB
 * snapshot after the mutation.
 *
 * Nothing updates or deletes this audit history.
 * ========================================================== */

create table
if not exists
public.cing_wallet_topup_promotion_history (
  id bigint
    generated by default as identity
    primary key,

  action text
    not null,

  actor_id text,

  snapshot jsonb
    not null,

  created_at timestamptz
    not null
    default clock_timestamp(),

  constraint
    cing_wallet_topup_promotion_history_action_ck
    check (
      action in (
        'configure',
        'disable'
      )
    ),

  constraint
    cing_wallet_topup_promotion_history_snapshot_ck
    check (
      jsonb_typeof(snapshot) = 'object'
    )
);

create index
if not exists
cing_wallet_topup_promotion_history_created_idx
on public.cing_wallet_topup_promotion_history (
  created_at desc,
  id desc
);


