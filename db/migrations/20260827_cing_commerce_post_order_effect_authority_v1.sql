/* ----------------------------------------------------------
 * ORDER POINT DEDUCT
 * ---------------------------------------------------------- */

create or replace function
public.cing_commerce_apply_order_points_deduct_v1(
  p_order_id bigint
)
returns table (
  order_id bigint,
  user_id text,
  points_deducted integer,
  balance_before integer,
  balance_after integer,
  applied boolean
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_player public.players%rowtype;

  v_user_id text;
  v_points integer;

  v_balance_numeric numeric;
  v_before integer;
  v_after integer;

  v_existing public.point_transactions%rowtype;
begin
  if p_order_id is null then
    raise exception
      'COMMERCE_POINT_DEDUCT_ORDER_REQUIRED'
      using errcode = '22023';
  end if;

  select o.*
  into v_order
  from public.orders o
  where o.id = p_order_id;

  if not found then
    raise exception
      'COMMERCE_POINT_DEDUCT_ORDER_NOT_FOUND'
      using errcode = 'P0002';
  end if;

  if v_order.payment_status is distinct from 'paid' then
    raise exception
      'COMMERCE_POINT_DEDUCT_ORDER_NOT_PAID'
      using errcode = '55000';
  end if;

  v_user_id :=
    nullif(
      btrim(
        coalesce(
          v_order.customer_phone,
          v_order.user_id,
          ''
        )
      ),
      ''
    );

  if v_user_id is null then
    raise exception
      'COMMERCE_POINT_DEDUCT_USER_MISSING'
      using errcode = '55000';
  end if;

  begin
    if v_order.points_used is null then
      v_points := 0;
    elsif v_order.points_used <> trunc(v_order.points_used)
       or v_order.points_used < 0
       or v_order.points_used > 2147483647 then
      raise exception
        'COMMERCE_POINT_DEDUCT_AMOUNT_INVALID'
        using errcode = '55000';
    else
      v_points :=
        v_order.points_used::integer;
    end if;
  exception
    when numeric_value_out_of_range then
      raise exception
        'COMMERCE_POINT_DEDUCT_AMOUNT_INVALID'
        using errcode = '55000';
  end;

  if v_points = 0 then
    return query
    select
      v_order.id,
      v_user_id,
      0,
      null::integer,
      null::integer,
      false;

    return;
  end if;

  /*
   * Exact forensic legacy fence.
   *
   * Orders 139 and 185 requested a deduction under the old
   * payment path, but that side effect provably never executed.
   * Replaying either order through the new authority must
   * preserve that historical fact: no balance mutation and no
   * fabricated point_transactions row.
   *
   * Do not replace this with a date/time cutoff.
   */
  if
    (
      v_order.id = 139
      and v_points = 5
    )
    or
    (
      v_order.id = 185
      and v_points = 30
    )
  then
    return query
    select
      v_order.id,
      v_user_id,
      v_points,
      null::integer,
      null::integer,
      false;

    return;
  end if;

  /*
   * Player row is the loyalty-balance serialization boundary.
   */
  select p.*
  into v_player
  from public.players p
  where p.user_id = v_user_id
  for update;

  if not found then
    raise exception
      'COMMERCE_POINT_DEDUCT_PLAYER_NOT_FOUND'
      using errcode = 'P0002';
  end if;

  /*
   * Recheck idempotency AFTER the serialization lock.
   */
  select pt.*
  into v_existing
  from public.point_transactions pt
  where pt.commerce_order_id = v_order.id
    and pt.transaction_type = 'deduct'
  limit 1;

  if found then
    return query
    select
      v_order.id,
      v_user_id,
      abs(v_existing.points)::integer,
      v_existing.balance_before::integer,
      v_existing.balance_after::integer,
      false;

    return;
  end if;

  v_balance_numeric :=
    coalesce(
      v_player.total_points,
      0
    );

  if v_balance_numeric <> trunc(v_balance_numeric)
     or v_balance_numeric < 0
     or v_balance_numeric > 2147483647 then
    raise exception
      'COMMERCE_POINT_BALANCE_DOMAIN_INVALID'
      using errcode = '55000';
  end if;

  v_before :=
    v_balance_numeric::integer;

  if v_before < v_points then
    raise exception
      'COMMERCE_POINT_DEDUCT_INSUFFICIENT_POINTS'
      using errcode = 'P0001';
  end if;

  v_after :=
    v_before - v_points;

  update public.players p
  set total_points = v_after
  where p.user_id = v_user_id;

  insert into public.point_transactions (
    user_id,
    commerce_order_id,
    transaction_type,
    points,
    balance_before,
    balance_after,
    reason,
    metadata
  )
  values (
    v_user_id,
    v_order.id,
    'deduct',
    -v_points,
    v_before,
    v_after,
    'Thanh toán đơn hàng ' || v_order.order_code,
    jsonb_build_object(
      'source',
      'commerce_order',
      'effect_key',
      'points_deduct',
      'order_code',
      v_order.order_code
    )
  );

  return query
  select
    v_order.id,
    v_user_id,
    v_points,
    v_before,
    v_after,
    true;
end;
$$;


/* ----------------------------------------------------------
 * ORDER AFTER-HOURS POINT EARN
 *
 * Existing production contract:
 *
 * member / loyal / silver / gold / diamond / partner = 10%
 * loyal_partner                                      = 15%
 *
 * points =
 * floor(total_amount * point_rate / 1000)
 *
 * PostgreSQL derives amount from canonical paid order.
 * ---------------------------------------------------------- */

create or replace function
public.cing_commerce_apply_order_points_earn_v1(
  p_order_id bigint,
  p_tier_key text
)
returns table (
  order_id bigint,
  user_id text,
  tier_key text,
  points_added integer,
  balance_before integer,
  balance_after integer,
  applied boolean
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_player public.players%rowtype;

  v_user_id text;
  v_tier text;

  v_rate numeric;
  v_amount numeric;
  v_points_numeric numeric;
  v_points integer;

  v_balance_numeric numeric;
  v_before integer;
  v_after integer;

  v_existing public.point_transactions%rowtype;
begin
  if p_order_id is null then
    raise exception
      'COMMERCE_POINT_EARN_ORDER_REQUIRED'
      using errcode = '22023';
  end if;

  select o.*
  into v_order
  from public.orders o
  where o.id = p_order_id;

  if not found then
    raise exception
      'COMMERCE_POINT_EARN_ORDER_NOT_FOUND'
      using errcode = 'P0002';
  end if;

  if v_order.payment_status is distinct from 'paid' then
    raise exception
      'COMMERCE_POINT_EARN_ORDER_NOT_PAID'
      using errcode = '55000';
  end if;

  v_user_id :=
    nullif(
      btrim(
        coalesce(
          v_order.customer_phone,
          v_order.user_id,
          ''
        )
      ),
      ''
    );

  if v_user_id is null then
    raise exception
      'COMMERCE_POINT_EARN_USER_MISSING'
      using errcode = '55000';
  end if;

  v_tier :=
    lower(
      btrim(
        coalesce(
          nullif(p_tier_key, ''),
          'member'
        )
      )
    );

  v_rate :=
    case v_tier
      when 'member' then 0.10
      when 'loyal' then 0.10
      when 'silver' then 0.10
      when 'gold' then 0.10
      when 'diamond' then 0.10
      when 'partner' then 0.10
      when 'loyal_partner' then 0.15
      else null
    end;

  if v_rate is null then
    raise exception
      'COMMERCE_POINT_EARN_TIER_INVALID'
      using errcode = '22023';
  end if;

  v_amount :=
    coalesce(
      v_order.total_amount,
      0
    );

  if v_amount <> trunc(v_amount)
     or v_amount < 0 then
    raise exception
      'COMMERCE_POINT_EARN_ORDER_AMOUNT_INVALID'
      using errcode = '55000';
  end if;

  v_points_numeric :=
    floor(
      (v_amount * v_rate) /
      1000
    );

  if v_points_numeric < 0
     or v_points_numeric > 2147483647 then
    raise exception
      'COMMERCE_POINT_EARN_AMOUNT_OUT_OF_RANGE'
      using errcode = '22003';
  end if;

  v_points :=
    v_points_numeric::integer;

  if v_points = 0 then
    return query
    select
      v_order.id,
      v_user_id,
      v_tier,
      0,
      null::integer,
      null::integer,
      false;

    return;
  end if;

  select p.*
  into v_player
  from public.players p
  where p.user_id = v_user_id
  for update;

  if not found then
    raise exception
      'COMMERCE_POINT_EARN_PLAYER_NOT_FOUND'
      using errcode = 'P0002';
  end if;

  /*
   * Recheck durable award AFTER player serialization.
   */
  select pt.*
  into v_existing
  from public.point_transactions pt
  where pt.commerce_order_id = v_order.id
    and pt.transaction_type = 'add'
  limit 1;

  if found then
    return query
    select
      v_order.id,
      v_user_id,
      v_tier,
      abs(v_existing.points)::integer,
      v_existing.balance_before::integer,
      v_existing.balance_after::integer,
      false;

    return;
  end if;

  v_balance_numeric :=
    coalesce(
      v_player.total_points,
      0
    );

  if v_balance_numeric <> trunc(v_balance_numeric)
     or v_balance_numeric < 0
     or v_balance_numeric > 2147483647 then
    raise exception
      'COMMERCE_POINT_BALANCE_DOMAIN_INVALID'
      using errcode = '55000';
  end if;

  v_before :=
    v_balance_numeric::integer;

  if
    v_before >
      2147483647 - v_points
  then
    raise exception
      'COMMERCE_POINT_EARN_BALANCE_OVERFLOW'
      using errcode = '22003';
  end if;

  v_after :=
    v_before + v_points;

  update public.players p
  set total_points = v_after
  where p.user_id = v_user_id;

  insert into public.point_transactions (
    user_id,
    commerce_order_id,
    transaction_type,
    points,
    balance_before,
    balance_after,
    reason,
    metadata
  )
  values (
    v_user_id,
    v_order.id,
    'add',
    v_points,
    v_before,
    v_after,
    'Tích điểm đơn hàng '
      || v_order.order_code
      || ' ('
      || v_tier
      || ')',
    jsonb_build_object(
      'source',
      'after_hours_app_order',
      'effect_key',
      'points_earn',
      'order_code',
      v_order.order_code,
      'tier',
      v_tier,
      'point_rate',
      v_rate
    )
  );

  return query
  select
    v_order.id,
    v_user_id,
    v_tier,
    v_points,
    v_before,
    v_after,
    true;
end;
