/*
 * ==========================================================
 * ORDER-SPEND GAME PLAY AWARD AUTHORITY V1
 * ==========================================================
 *
 * Reuses public.game_play_transactions as the authoritative
 * game-play ledger.
 *
 * One commerce order may award game plays at most once.
 *
 * Atomic PostgreSQL transaction owns:
 *
 *   players.game_plays
 *   players.plays_from_spend
 *   game_play_transactions
 *   analytics_events compatibility projection
 *
 * Node check-before-write is not authority.
 */


/*
 * Durable reference fence for non-session game-play mutations.
 *
 * Existing integration-test cleanup rows remain compatible.
 * The uniqueness scope is intentionally limited to
 * order_spending.
 */
create unique index if not exists
game_play_transactions_order_spending_uq
on public.game_play_transactions (
  reference_type,
  reference_id
)
where
  reference_type = 'order_spending'
  and reference_id is not null;


/*
 * Commerce order-spend award.
 *
 * Caller supplies only canonical commerce order identity.
 * User, amount and threshold are resolved inside PostgreSQL.
 */
create or replace function
public.cing_commerce_award_order_spend_plays_v1(
  p_order_id bigint
)
returns table (
  order_id bigint,
  user_id text,
  order_code text,
  order_amount bigint,
  spend_per_play bigint,
  plays_awarded integer,
  balance_before integer,
  balance_after integer,
  plays_from_spend_after integer,
  replayed boolean
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order
    public.orders%rowtype;

  v_player
    public.players%rowtype;

  v_existing
    public.game_play_transactions%rowtype;

  v_spend_per_play bigint;

  v_amount bigint;

  v_plays integer;

  v_before integer;

  v_after integer;

  v_from_spend_after integer;

  v_user_id text;

  v_now timestamptz :=
    clock_timestamp();

  v_reference_id text;
begin
  if p_order_id is null then
    raise exception
      'COMMERCE_ORDER_ID_REQUIRED'
      using errcode = '22023';
  end if;


  /*
   * Canonical durable commerce order is authoritative.
   */
  select o.*
  into v_order
  from public.orders o
  where o.id = p_order_id
  for update;

  if not found then
    raise exception
      'COMMERCE_ORDER_NOT_FOUND'
      using errcode = 'P0002';
  end if;


  if v_order.payment_status <> 'paid' then
    raise exception
      'COMMERCE_ORDER_NOT_PAID'
      using errcode = '55000';
  end if;


  if v_order.payment_transaction_id is null then
    raise exception
      'COMMERCE_ORDER_PAYMENT_LINK_REQUIRED'
      using errcode = '55000';
  end if;


  /*
   * Payment projection must point back to this exact order.
   */
  if not exists (
    select 1
    from public.payment_transactions p
    where p.id =
      v_order.payment_transaction_id
      and p.order_created is true
      and p.order_id =
        v_order.id
      and p.payment_status = 'paid'
      and p.payment_purpose = 'order'
  ) then
    raise exception
      'COMMERCE_ORDER_PAYMENT_AUTHORITY_INVALID'
      using errcode = '55000';
  end if;


  v_user_id :=
    btrim(
      coalesce(
        nullif(v_order.user_id, ''),
        nullif(v_order.customer_phone, ''),
        ''
      )
    );

  if v_user_id = '' then
    raise exception
      'COMMERCE_ORDER_USER_REQUIRED'
      using errcode = '55000';
  end if;


  v_reference_id :=
    v_order.id::text;


  /*
   * Durable idempotent replay before any balance mutation.
   */
  select t.*
  into v_existing
  from public.game_play_transactions t
  where t.reference_type =
      'order_spending'
    and t.reference_id =
      v_reference_id;

  if found then
    if
      v_existing.user_id <>
        v_user_id
      or v_existing.transaction_type <>
        'add'
      or v_existing.amount <= 0
      or v_existing.balance_after <>
        v_existing.balance_before
        + v_existing.amount
    then
      raise exception
        'COMMERCE_ORDER_SPEND_PLAY_REPLAY_CONFLICT'
        using errcode = '55000';
    end if;

    return query
    select
      v_order.id,
      v_user_id,
      v_order.order_code,
      greatest(
        coalesce(
          v_order.subtotal,
          0
        ),
        0
      )::bigint,
      coalesce(
        nullif(
          (
            v_existing.metadata
              ->> 'spend_per_play'
          )::bigint,
          0
        ),
        0
      ),
      v_existing.amount,
      v_existing.balance_before,
      v_existing.balance_after,
      coalesce(
        (
          v_existing.metadata
            ->> 'plays_from_spend_after'
        )::integer,
        0
      ),
      true;

    return;
  end if;


  /*
   * Preserve existing production semantics:
   * spend reward excludes shipping whenever subtotal exists.
   */
  v_amount :=
    case
      when coalesce(
        v_order.subtotal,
        0
      ) > 0
      then v_order.subtotal::bigint

      else greatest(
        coalesce(
          v_order.total_amount,
          0
        )
        -
        coalesce(
          v_order.shipping_fee,
          0
        ),
        0
      )::bigint
    end;


  if v_amount <= 0 then
    /*
     * Zero-award orders need no balance mutation. They are not
     * inserted into game_play_transactions because that ledger
     * explicitly forbids amount = 0.
     */
    return query
    select
      v_order.id,
      v_user_id,
      v_order.order_code,
      v_amount,
      0::bigint,
      0,
      0,
      0,
      0,
      false;

    return;
  end if;


  select
    coalesce(
      nullif(
        c.spend_per_play,
        0
      ),
      20000
    )::bigint
  into v_spend_per_play
  from public.app_configs c
  where c.id = 1;

  if
    v_spend_per_play is null
    or v_spend_per_play <= 0
  then
    raise exception
      'COMMERCE_SPEND_PER_PLAY_INVALID'
      using errcode = '55000';
  end if;


  v_plays :=
    floor(
      v_amount::numeric
      /
      v_spend_per_play::numeric
    )::integer;


  if v_plays <= 0 then
    return query
    select
      v_order.id,
      v_user_id,
      v_order.order_code,
      v_amount,
      v_spend_per_play,
      0,
      0,
      0,
      0,
      false;

    return;
  end if;


  /*
   * Player row lock serializes all commerce-award mutation for
   * this user.
   */
  select p.*
  into v_player
  from public.players p
  where p.user_id =
    v_user_id
  for update;

  if not found then
    raise exception
      'PLAYER_NOT_FOUND'
      using errcode = 'P0002';
  end if;


  /*
   * Recheck idempotency AFTER player lock. A concurrent request
   * may have passed the optimistic replay check before waiting.
   */
  select t.*
  into v_existing
  from public.game_play_transactions t
  where t.reference_type =
      'order_spending'
    and t.reference_id =
      v_reference_id;

  if found then
    return query
    select
      v_order.id,
      v_user_id,
      v_order.order_code,
      v_amount,
      coalesce(
        (
          v_existing.metadata
            ->> 'spend_per_play'
        )::bigint,
        v_spend_per_play
      ),
      v_existing.amount,
      v_existing.balance_before,
      v_existing.balance_after,
      coalesce(
        (
          v_existing.metadata
            ->> 'plays_from_spend_after'
        )::integer,
        coalesce(
          v_player.plays_from_spend,
          0
        )
      ),
      true;

    return;
  end if;


  v_before :=
    coalesce(
      v_player.game_plays,
      0
    );

  update public.players p
  set
    game_plays =
      coalesce(
        p.game_plays,
        0
      )
      + v_plays,

    plays_from_spend =
      coalesce(
        p.plays_from_spend,
        0
      )
      + v_plays,

    updated_at =
      v_now

  where p.user_id =
    v_user_id

  returning
    p.game_plays,
    p.plays_from_spend

  into
    v_after,
    v_from_spend_after;


  if v_after <>
    v_before + v_plays
  then
    raise exception
      'COMMERCE_ORDER_SPEND_PLAY_BALANCE_INVARIANT'
      using errcode = '55000';
  end if;


  insert into
  public.game_play_transactions (
    user_id,
    transaction_type,
    amount,
    balance_before,
    balance_after,
    reason,
    game_key,
    session_id,
    reference_type,
    reference_id,
    metadata,
    created_at
  )
  values (
    v_user_id,
    'add',
    v_plays,
    v_before,
    v_after,
    format(
      'Tiêu dùng %sđ — đơn %s',
      v_amount,
      v_order.order_code
    ),
    null,
    null,
    'order_spending',
    v_reference_id,
    jsonb_build_object(
      'source',
        'order_spending',
      'order_id',
        v_order.id,
      'order_code',
        v_order.order_code,
      'order_amount',
        v_amount,
      'spend_per_play',
        v_spend_per_play,
      'plays_from_spend_after',
        v_from_spend_after
    ),
    v_now
  );


  /*
   * Backward-compatible profile history projection.
   *
   * This is committed in the same transaction as authoritative
   * ledger + balance mutation.
   */
  insert into
  public.analytics_events (
    user_id,
    event_name,
    event_data,
    metadata,
    created_at
  )
  values (
    v_user_id,
    'plays_added',
    jsonb_build_object(
      'amount',
        v_plays,
      'reason',
        format(
          'Tiêu dùng %sđ — đơn %s',
          v_amount,
          v_order.order_code
        ),
      'source',
        'order_spending',
      'new_total',
        v_after,
      'order_code',
        v_order.order_code,
      'order_amount',
        v_amount,
      'spend_per_play',
        v_spend_per_play
    ),
    jsonb_build_object(
      'order_id',
        v_order.id,
      'reference_type',
        'order_spending',
      'reference_id',
        v_reference_id
    ),
    v_now
  );


  return query
  select
    v_order.id,
    v_user_id,
    v_order.order_code,
    v_amount,
    v_spend_per_play,
    v_plays,
    v_before,
    v_after,
    v_from_spend_after,
    false;
end;
$$;


