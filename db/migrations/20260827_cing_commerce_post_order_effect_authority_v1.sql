    last_error =
      left(
        coalesce(
          nullif(
            btrim(p_error),
            ''
          ),
          'unknown_error'
        ),
        4000
      ),
    updated_at = v_now
  where id = v_effect.id
  returning *
  into v_effect;

  return v_effect;
end;
$$;


