/*
 * ==========================================================
 * CING COMMERCE — ORDER LOYALTY POINT EFFECT AUTHORITY V1
 * ==========================================================
 *
 * point_transactions is the durable loyalty ledger.
 * players.total_points is the serialized balance projection.
 *
 * These functions intentionally do NOT call iPOS.
 * External iPOS delivery remains application orchestration.
 *
 * points_deduct:
 * - derives user and points from canonical paid order
 * - serializes on players row
 * - fails closed on insufficient / invalid balance
 * - writes balance + durable ledger atomically
 * - exactly once per order
 *
 * points_earn:
 * - derives user / amount from canonical paid order
 * - accepts tier only as the already-resolved commerce tier
 * - PostgreSQL owns the actual point arithmetic
 * - intended only for the existing after-hours local-award path
 * - exactly once per order
 */


/* ----------------------------------------------------------
 * Dedicated Commerce identity on the shared loyalty ledger.
 *
 * point_transactions.order_id is a pre-existing nullable UUID
 * legacy field. Canonical Commerce orders use bigint identity.
 * The legacy UUID column is intentionally preserved unchanged.
 * ---------------------------------------------------------- */

alter table public.point_transactions
add column if not exists
  commerce_order_id bigint;

do $commerce_point_order_fk$
begin
  if not exists (
    select 1
    from pg_constraint c
    join pg_class r
      on r.oid = c.conrelid
    join pg_namespace n
      on n.oid = r.relnamespace
    where n.nspname = 'public'
      and r.relname = 'point_transactions'
      and c.conname =
        'point_transactions_commerce_order_fk'
  ) then
    alter table public.point_transactions
    add constraint
      point_transactions_commerce_order_fk
    foreign key (commerce_order_id)
    references public.orders(id)
    on delete restrict;
  end if;
end;
$commerce_point_order_fk$;


/* ----------------------------------------------------------
 * HISTORICAL POINT-DEDUCTION CLASSIFICATION V1
 *
 * Production forensic audit proved that orders 139 and 185
 * requested loyalty-point deductions, but the legacy deduction
 * side effect did NOT execute.
 *
 * Root cause:
 * the pre-4297e0e payment path passed payment.user_id (UUID)
 * into deductPoints() as the players.user_id lookup identity.
 * The lookup therefore resolved no loyalty player, interpreted
 * the balance as zero, and threw before UPDATE.
 *
 * These are NOT historical deductions and MUST NOT be
 * reconstructed in point_transactions.
 *
 * They are durable known legacy non-executed effects:
 *
 *   139 -> points_used  5 -> NOT_EXECUTED
 *   185 -> points_used 30 -> NOT_EXECUTED
 *
 * IMPORTANT:
 * this classification is intentionally exact-order only.
 * Commit time 4297e0e is not used as a production deployment
 * cutoff because source commit time does not prove deployment
 * time.
 *
 * Fresh/staging environments containing neither production
 * order may apply this migration. A partial or changed forensic
 * dataset fails closed.
 * ---------------------------------------------------------- */

do $legacy_point_deduct_shape$
declare
  v_target_count integer;
begin
  select count(*)
  into v_target_count
  from public.orders
  where id in (
    139,
    185
  );

  if v_target_count > 0 then
    if v_target_count <> 2 then
      raise exception
        'COMMERCE_LEGACY_POINT_DEDUCT_ORDER_SET_CHANGED'
        using errcode = '55000';
    end if;

    /*
     * Exact forensic order shape. Do not generalize this into
     * a timestamp cutoff.
     */
    if (
      select count(*)
      from public.orders o
      where
        (
          o.id = 139
          and o.points_used = 5
          and o.payment_status = 'paid'
        )
        or
        (
          o.id = 185
          and o.points_used = 30
          and o.payment_status = 'paid'
        )
    ) <> 2 then
      raise exception
        'COMMERCE_LEGACY_POINT_DEDUCT_ORDER_SHAPE_CHANGED'
        using errcode = '55000';
    end if;

    /*
     * A reconstructed deduction would falsify history.
     */
    if exists (
      select 1
      from public.point_transactions pt
      where pt.commerce_order_id in (
        139,
        185
      )
        and pt.transaction_type = 'deduct'
    ) then
      raise exception
        'COMMERCE_LEGACY_POINT_DEDUCT_UNEXPECTED_LEDGER'
        using errcode = '55000';
    end if;
  end if;
end;
$legacy_point_deduct_shape$;


