/*
 * ==========================================================
 * ORDER-SPEND GAME PLAY HISTORICAL BACKFILL V1
 * ==========================================================
 *
 * Production forensic audit identified exactly four canonical
 * commerce orders that were already awarded plays by the
 * legacy Node path before game_play_transactions became the
 * durable order-spending authority:
 *
 *   order 377 -> analytics 2225 -> +1
 *   order 379 -> analytics 2314 -> +1
 *   order 382 -> analytics 3180 -> +1
 *   order 387 -> analytics 3717 -> +22
 *
 * This section reconstructs authoritative ledger history only.
 *
 * CRITICAL:
 * - players.game_plays MUST NOT be changed.
 * - players.plays_from_spend MUST NOT be changed.
 * - analytics_events MUST NOT be duplicated.
 *
 * The existing legacy award already changed the balance.
 */


/*
 * Fail closed if a partial historical dataset is present.
 *
 * Fresh/staging environments with none of these production
 * records may apply the migration without backfill.
 */
do $historical_shape$
declare
  v_target_order_count integer;
  v_target_event_count integer;
  v_existing_ledger_count integer;
begin
  select count(*)
  into v_target_order_count
  from public.orders
  where id in (
    377,
    379,
    382,
    387
  );

  select count(*)
  into v_target_event_count
  from public.analytics_events
  where id in (
    2225,
    2314,
    3180,
    3717
  );

  if
    v_target_order_count > 0
    or v_target_event_count > 0
  then
    if v_target_order_count <> 4 then
      raise exception
        'COMMERCE_ORDER_SPEND_PLAY_BACKFILL_ORDER_SET_CHANGED'
        using errcode = '55000';
    end if;

    if v_target_event_count <> 4 then
      raise exception
        'COMMERCE_ORDER_SPEND_PLAY_BACKFILL_EVENT_SET_CHANGED'
        using errcode = '55000';
    end if;


    /*
     * Canonical payment/order authority must remain intact.
     */
    if (
      select count(*)
      from public.orders o
      join public.payment_transactions p
        on p.id =
          o.payment_transaction_id
      where o.id in (
        377,
        379,
        382,
        387
      )
        and o.payment_status = 'paid'
        and p.payment_status = 'paid'
        and p.payment_purpose = 'order'
        and p.order_created is true
        and p.order_id = o.id
    ) <> 4 then
      raise exception
        'COMMERCE_ORDER_SPEND_PLAY_BACKFILL_PAYMENT_AUTHORITY_CHANGED'
        using errcode = '55000';
    end if;


    /*
     * Exact audited event/order pairing must remain unchanged.
     */
    if (
      select count(*)
      from public.analytics_events ae
      join public.orders o
        on o.order_code =
          ae.event_data ->> 'order_code'
      where
        (
          ae.id = 2225
          and o.id = 377
          and ae.user_id = '0984966336'
          and (ae.event_data ->> 'amount')::integer = 1
          and (ae.event_data ->> 'new_total')::integer = 885
          and (ae.event_data ->> 'order_amount')::bigint = 20100
          and (ae.event_data ->> 'spend_per_play')::bigint = 20000
        )
        or
        (
          ae.id = 2314
          and o.id = 379
          and ae.user_id = '0984966336'
          and (ae.event_data ->> 'amount')::integer = 1
          and (ae.event_data ->> 'new_total')::integer = 889
          and (ae.event_data ->> 'order_amount')::bigint = 20250
          and (ae.event_data ->> 'spend_per_play')::bigint = 20000
        )
        or
        (
          ae.id = 3180
          and o.id = 382
          and ae.user_id = '0984966336'
          and (ae.event_data ->> 'amount')::integer = 1
          and (ae.event_data ->> 'new_total')::integer = 837
          and (ae.event_data ->> 'order_amount')::bigint = 20100
          and (ae.event_data ->> 'spend_per_play')::bigint = 20000
        )
        or
        (
          ae.id = 3717
          and o.id = 387
          and ae.user_id = '0983651389'
          and (ae.event_data ->> 'amount')::integer = 22
          and (ae.event_data ->> 'new_total')::integer = 22
          and (ae.event_data ->> 'order_amount')::bigint = 443000
          and (ae.event_data ->> 'spend_per_play')::bigint = 20000
        )
    ) <> 4 then
      raise exception
        'COMMERCE_ORDER_SPEND_PLAY_BACKFILL_EVENT_SHAPE_CHANGED'
        using errcode = '55000';
    end if;


    /*
     * Identity must still agree with canonical commerce order.
     */
    if exists (
      select 1
      from public.analytics_events ae
      join public.orders o
        on o.order_code =
          ae.event_data ->> 'order_code'
      where ae.id in (
        2225,
        2314,
        3180,
        3717
      )
        and ae.user_id <>
          coalesce(
            nullif(o.user_id, ''),
            nullif(o.customer_phone, ''),
            ''
          )
    ) then
      raise exception
        'COMMERCE_ORDER_SPEND_PLAY_BACKFILL_IDENTITY_CHANGED'
        using errcode = '55000';
    end if;


    select count(*)
    into v_existing_ledger_count
    from public.game_play_transactions
    where reference_type =
        'order_spending'
      and reference_id in (
        '377',
        '379',
        '382',
        '387'
      );

    if v_existing_ledger_count <> 0 then
      raise exception
        'COMMERCE_ORDER_SPEND_PLAY_BACKFILL_ALREADY_PRESENT'
        using errcode = '55000';
    end if;
  end if;
end;
$historical_shape$;


/*
 * Reconstruct the four durable ledger rows from immutable
 * compatibility history.
 *
 * balance_before is derived from:
 *
 *   balance_after - awarded amount
 */
insert into
public.game_play_transactions (
  user_id,
  transaction_type,
  amount,
  balance_before,
  balance_after,
  reason,
  game_key,
  session_id,
  reference_type,
  reference_id,
  metadata,
  created_at
)
select
  ae.user_id,

  'add',

  (ae.event_data ->> 'amount')::integer,

  (
    (ae.event_data ->> 'new_total')::integer
    -
    (ae.event_data ->> 'amount')::integer
  ),

  (ae.event_data ->> 'new_total')::integer,

  coalesce(
    nullif(
      ae.event_data ->> 'reason',
      ''
    ),
    format(
      'Tiêu dùng %sđ — đơn %s',
      ae.event_data ->> 'order_amount',
      o.order_code
    )
  ),

  null,

  null,

  'order_spending',

  o.id::text,

  jsonb_build_object(
    'source',
      'order_spending',

    'historical_backfill',
      true,

    'historical_analytics_event_id',
      ae.id,

    'order_id',
      o.id,

    'order_code',
      o.order_code,

    'order_amount',
      (ae.event_data ->> 'order_amount')::bigint,

    'spend_per_play',
      (ae.event_data ->> 'spend_per_play')::bigint
  ),

  ae.created_at

from public.analytics_events ae

join public.orders o
  on o.order_code =
    ae.event_data ->> 'order_code'

where (
  (
    ae.id = 2225
    and o.id = 377
  )
  or
  (
    ae.id = 2314
    and o.id = 379
  )
  or
  (
    ae.id = 3180
    and o.id = 382
  )
  or
  (
    ae.id = 3717
    and o.id = 387
  )
)

on conflict (
  reference_type,
  reference_id
)
where
  reference_type =
    'order_spending'
  and reference_id is not null

do nothing;


