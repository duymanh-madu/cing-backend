begin;

/*
 * ==========================================================
 * CING COMMERCE — POST-ORDER EFFECT AUTHORITY V1
 * ==========================================================
 *
 * Purpose:
 * provide durable, per-order, per-effect execution authority
 * for business effects that happen after canonical commerce
 * order creation.
 *
 * This migration intentionally does NOT switch the production
 * processor yet.
 *
 * Core guarantees:
 * - one durable row per (order_id, effect_key)
 * - PostgreSQL owns claim / lease / retry state
 * - concurrent workers cannot own the same live lease
 * - completed effects are immutable terminal successes
 * - failed / abandoned execution can be reclaimed
 * - Node/Redis are orchestration/optimization only
 */

create table if not exists
public.cing_commerce_order_effects (
  id bigint generated by default as identity primary key,

  order_id bigint not null
    references public.orders(id)
    on delete restrict,

  effect_key text not null,

  status text not null
    default 'pending',

  attempt_count integer not null
    default 0,

  claim_token uuid,

  claimed_at timestamptz,

  lease_expires_at timestamptz,

  completed_at timestamptz,

  last_error text,

  created_at timestamptz not null
    default now(),

  updated_at timestamptz not null
    default now(),

  constraint
    cing_commerce_order_effects_effect_key_ck
    check (
      effect_key in (
        'ipos_delivery',
        'game_plays',
        'daily_mission',
        'partner_spending',
        'local_spending',
        'points_deduct',
        'points_earn'
      )
    ),

  constraint
    cing_commerce_order_effects_status_ck
    check (
      status in (
        'pending',
        'processing',
        'completed',
        'failed'
      )
    ),

  constraint
    cing_commerce_order_effects_attempt_count_ck
    check (
      attempt_count >= 0
    ),

  constraint
    cing_commerce_order_effects_processing_ck
    check (
      (
        status = 'processing'
        and claim_token is not null
        and claimed_at is not null
        and lease_expires_at is not null
        and completed_at is null
      )
      or
      (
        status <> 'processing'
        and claim_token is null
        and claimed_at is null
        and lease_expires_at is null
      )
    ),

  constraint
    cing_commerce_order_effects_completed_ck
    check (
      (
        status = 'completed'
        and completed_at is not null
      )
      or
      (
        status <> 'completed'
        and completed_at is null
      )
    )
);

create unique index if not exists
cing_commerce_order_effects_order_effect_uq
on public.cing_commerce_order_effects (
  order_id,
  effect_key
);

create index if not exists
cing_commerce_order_effects_retry_idx
on public.cing_commerce_order_effects (
  status,
  lease_expires_at,
  updated_at
);

revoke all
on public.cing_commerce_order_effects
from public, anon, authenticated;

grant select
on public.cing_commerce_order_effects
to service_role;


/*
 * ----------------------------------------------------------
 * Ensure one effect row exists.
 * ----------------------------------------------------------
 *
 * Safe under concurrent insertion because the durable UNIQUE
 * constraint owns idempotency.
 */
create or replace function
public.cing_commerce_ensure_order_effect_v1(
  p_order_id bigint,
  p_effect_key text
)
returns public.cing_commerce_order_effects
language plpgsql
security definer
set search_path = public
as $$
declare
  v_effect
    public.cing_commerce_order_effects%rowtype;
begin
  if p_order_id is null then
    raise exception
      'COMMERCE_EFFECT_ORDER_ID_REQUIRED'
      using errcode = '22023';
  end if;

  if p_effect_key is null
     or btrim(p_effect_key) = '' then
    raise exception
      'COMMERCE_EFFECT_KEY_REQUIRED'
      using errcode = '22023';
  end if;

  if not exists (
    select 1
    from public.orders
    where id = p_order_id
  ) then
    raise exception
      'COMMERCE_EFFECT_ORDER_NOT_FOUND'
      using errcode = 'P0002';
  end if;

  insert into
    public.cing_commerce_order_effects (
      order_id,
      effect_key
    )
  values (
    p_order_id,
    p_effect_key
  )
  on conflict (
    order_id,
    effect_key
  )
  do nothing;

  select *
  into v_effect
  from public.cing_commerce_order_effects
  where order_id = p_order_id
    and effect_key = p_effect_key;

  return v_effect;
end;
$$;


/*
 * ----------------------------------------------------------
 * Claim / reclaim one effect.
 * ----------------------------------------------------------
 */
create or replace function
public.cing_commerce_claim_order_effect_v1(
  p_order_id bigint,
  p_effect_key text,
  p_lease_seconds integer default 120
)
returns table (
  effect_id bigint,
  order_id bigint,
  effect_key text,
  status text,
  attempt_count integer,
  claim_token uuid,
  lease_expires_at timestamptz,
  completed_at timestamptz,
  acquired boolean
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_effect
    public.cing_commerce_order_effects%rowtype;

  v_now timestamptz :=
    clock_timestamp();

  v_token uuid;
begin
  if p_lease_seconds is null
     or p_lease_seconds < 1
     or p_lease_seconds > 3600 then
    raise exception
      'COMMERCE_EFFECT_LEASE_INVALID'
      using errcode = '22023';
  end if;

  perform
    public.cing_commerce_ensure_order_effect_v1(
      p_order_id,
      p_effect_key
    );

  select e.*
  into v_effect
  from public.cing_commerce_order_effects e
  where e.order_id = p_order_id
    and e.effect_key = p_effect_key
  for update;

  if v_effect.status = 'completed' then
    return query
    select
      v_effect.id,
      v_effect.order_id,
      v_effect.effect_key,
      v_effect.status,
      v_effect.attempt_count,
      v_effect.claim_token,
      v_effect.lease_expires_at,
      v_effect.completed_at,
      false;

    return;
  end if;

  if v_effect.status = 'processing'
     and v_effect.lease_expires_at > v_now then
    return query
    select
      v_effect.id,
      v_effect.order_id,
      v_effect.effect_key,
      v_effect.status,
      v_effect.attempt_count,
      v_effect.claim_token,
      v_effect.lease_expires_at,
      v_effect.completed_at,
      false;

    return;
  end if;

  v_token :=
    gen_random_uuid();

  update
    public.cing_commerce_order_effects e
  set
    status = 'processing',
    attempt_count =
      e.attempt_count + 1,
    claim_token =
      v_token,
    claimed_at =
      v_now,
    lease_expires_at =
      v_now
      + make_interval(
          secs => p_lease_seconds
        ),
    completed_at =
      null,
    last_error =
      null,
    updated_at =
      v_now
  where e.id = v_effect.id
  returning e.*
  into v_effect;

  return query
  select
    v_effect.id,
    v_effect.order_id,
    v_effect.effect_key,
    v_effect.status,
    v_effect.attempt_count,
    v_effect.claim_token,
    v_effect.lease_expires_at,
    v_effect.completed_at,
    true;
end;
$$;

/*
 * ----------------------------------------------------------
 * Complete effect.
 *
 * Exact claim token is mandatory. A stale worker cannot mark
 * a reclaimed effect completed.
 * ----------------------------------------------------------
 */
create or replace function
public.cing_commerce_complete_order_effect_v1(
  p_order_id bigint,
  p_effect_key text,
  p_claim_token uuid
)
returns public.cing_commerce_order_effects
language plpgsql
security definer
set search_path = public
as $$
declare
  v_effect
    public.cing_commerce_order_effects%rowtype;

  v_now timestamptz :=
    clock_timestamp();
begin
  if p_claim_token is null then
    raise exception
      'COMMERCE_EFFECT_CLAIM_TOKEN_REQUIRED'
      using errcode = '22023';
  end if;

  select *
  into v_effect
  from public.cing_commerce_order_effects
  where order_id = p_order_id
    and effect_key = p_effect_key
  for update;

  if not found then
    raise exception
      'COMMERCE_EFFECT_NOT_FOUND'
      using errcode = 'P0002';
  end if;

  if v_effect.status = 'completed' then
    return v_effect;
  end if;

  if v_effect.status <> 'processing'
     or v_effect.claim_token
        is distinct from p_claim_token then
    raise exception
      'COMMERCE_EFFECT_CLAIM_MISMATCH'
      using errcode = '55000';
  end if;

  update
    public.cing_commerce_order_effects
  set
    status = 'completed',
    claim_token = null,
    claimed_at = null,
    lease_expires_at = null,
    completed_at = v_now,
    last_error = null,
    updated_at = v_now
  where id = v_effect.id
  returning *
  into v_effect;

  return v_effect;
end;
$$;


